#!/usr/bin/env bash
# Setup-livekit.sh generates the LiveKit credentials and server config.
#
# Usage:
#   bash deploy/setup-livekit.sh            # generate missing files, keep existing
#   bash deploy/setup-livekit.sh --force    # re-render livekit.yaml from the env
#
# Installs (never committed; both mode 600):
#   data/kalanidhi/livekit.env     LIVEKIT_API_KEY / LIVEKIT_API_SECRET / LIVEKIT_KEYS
#   data/kalanidhi/livekit.yaml    server config rendered from that env
#
# The API keypair is generated once. To rotate it, remove both files and run
# again, then redeploy livekit and kalanidhi.
set -euo pipefail

source "$(cd "$(dirname "$0")" && pwd)/lib.sh"

KALANIDHI_DATA="$DATA_DIR/kalanidhi"
ENV_SRC="$REPO_DIR/services/env/livekit.env.example"
CONFIG_SRC="$REPO_DIR/services/livekit/config.example.yaml"
ENV_OUT="$KALANIDHI_DATA/livekit.env"
CONFIG_OUT="$KALANIDHI_DATA/livekit.yaml"
APP_ENV="$KALANIDHI_DATA/.env"
FORCE=false

usage() {
	cat <<'EOF'
Setup-livekit.sh generates the LiveKit credentials and server config.

Usage:
  bash deploy/setup-livekit.sh            # generate missing files, keep existing
  bash deploy/setup-livekit.sh --force    # re-render livekit.yaml from the env

Existing credentials are kept. To rotate the keypair, remove livekit.env and
livekit.yaml, then run again.
EOF
}

case "${1:-}" in
--force) FORCE=true ;;
-h | --help)
	usage
	exit 0
	;;
"") ;;
*)
	die "unknown option: $1 (see --help)"
	;;
esac

need_cmd openssl
[ -f "$ENV_SRC" ] || die "missing template: $ENV_SRC"
[ -f "$CONFIG_SRC" ] || die "missing template: $CONFIG_SRC"

if [ -e "$ENV_OUT" ]; then
	keep_existing "$ENV_OUT"
else
	key="${LIVEKIT_API_KEY:-$(new_hex 16)}"
	secret="${LIVEKIT_API_SECRET:-$(new_hex 32)}"
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' EXIT
	sed -e "s|{{LIVEKIT_API_KEY}}|$key|g" \
		-e "s|{{LIVEKIT_API_SECRET}}|$secret|g" "$ENV_SRC" >"$tmp"
	grep -q '{{' "$tmp" && die "unrendered placeholder in $ENV_SRC"
	install_file "$tmp" "$ENV_OUT" 600
	trap - EXIT
	rm -f "$tmp"
	echo "wrote $ENV_OUT (600, contains the API keypair; never commit)"
fi

key="$(env_value "$ENV_OUT" LIVEKIT_API_KEY)"
secret="$(env_value "$ENV_OUT" LIVEKIT_API_SECRET)"
[ -n "$key" ] && [ -n "$secret" ] || die "$ENV_OUT is missing LIVEKIT_API_KEY/LIVEKIT_API_SECRET"

if [ -e "$CONFIG_OUT" ] && ! $FORCE; then
	keep_existing "$CONFIG_OUT"
else
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' EXIT
	sed -e "s|{{LIVEKIT_API_KEY}}|$key|g" \
		-e "s|{{LIVEKIT_API_SECRET}}|$secret|g" "$CONFIG_SRC" >"$tmp"
	grep -q '{{' "$tmp" && die "unrendered placeholder in $CONFIG_SRC"
	if command -v python3 >/dev/null 2>&1 && python3 -c 'import yaml' 2>/dev/null; then
		python3 -c 'import sys, yaml; yaml.safe_load(open(sys.argv[1]))' "$tmp" ||
			die "generated LiveKit config is not valid YAML"
	fi
	install_file "$tmp" "$CONFIG_OUT" 600
	trap - EXIT
	rm -f "$tmp"
	echo "wrote $CONFIG_OUT (600, rendered from $ENV_OUT)"
fi

# App env: the container reaches the SFU on the compose network; browsers use
# the public WSS route. The API keypair arrives through env_file, not here.
if [ ! -e "$APP_ENV" ]; then
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' EXIT
	cat >"$tmp" <<'EOF'
# KalaNidhi runtime environment. Generated by deploy/setup-livekit.sh; edit
# values here, never in the repo. Convex URLs are added by setup-convex.sh.
LIVEKIT_URL=http://livekit:7880
NEXT_PUBLIC_LIVEKIT_URL=wss://livekit.kalanidhi.site
EOF
	install_file "$tmp" "$APP_ENV" 600
	trap - EXIT
	rm -f "$tmp"
	echo "wrote $APP_ENV (600)"
else
	env_ensure "$APP_ENV" LIVEKIT_URL "http://livekit:7880"
	env_ensure "$APP_ENV" NEXT_PUBLIC_LIVEKIT_URL "wss://livekit.kalanidhi.site"
fi

echo
echo "KalaNidhi loads LIVEKIT_API_KEY/LIVEKIT_API_SECRET from $ENV_OUT via compose."
echo "next: deploy livekit-redis, livekit, then kalanidhi"
